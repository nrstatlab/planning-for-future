#!/usr/bin/env python3
"""Build books.html -- every textbook the course pages recommend, in one place.

This page is GENERATED from two sources, so nothing on it is typed twice:
  * the textbook section of each course page (an <h2> such as "Recommended
    Textbooks", "Textbooks" or "Prescribed Textbooks & References");
  * the "## Textbooks" section of each Data Science course README, which the
    course page does not show (build_site.py keeps only the prose above the
    units).
Each book is listed once, with every course that recommends it and a link that
finds it on Amazon.in.

AMAZON_TAG is the owner's Amazon Associates tracking ID. While it is empty the
links are plain searches and the page claims nothing. Once it is set, every
link carries the tag, is marked rel="sponsored", and the page and the About
page say, as Amazon requires, that the site earns from qualifying purchases.

    python3 tools/build_books.py            # dry run: what would be listed
    python3 tools/build_books.py --apply    # write books.html and about.html's note
"""
import html as html_mod
import importlib.util
import pathlib
import re
import sys
from urllib.parse import quote_plus

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "books.html"
ABOUT = ROOT / "about.html"

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from stubs import is_stub  # noqa: E402

_spec = importlib.util.spec_from_file_location(
    "_bs", ROOT / "tools" / "data-science" / "build_site.py")
_bs = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_bs)
SITE_BASE = _bs.SITE_BASE

# The owner's Amazon Associates India tracking ID, e.g. "statstricks-21".
AMAZON_TAG = ""

AREAS = [("statistics", "Statistics"), ("data-science", "Data Science"), ("exams", "Examinations")]
BOOK_HEAD = re.compile(r'<h2 id="([^"]*)">([^<]*)</h2>')
BOOK_WORDS = re.compile(r"book|reference|literature", re.I)
MD_HEAD = re.compile(r"^## (Textbooks?|Text books|Textbooks and references|References)\b.*$", re.M)
DISCLOSURE = ("As an Amazon Associate, StatsTricks360 earns from qualifying purchases made "
              "through these links, at no extra cost to you.")
NOTE_START = "<!-- books-note: generated by tools/build_books.py -->"
NOTE_END = "<!-- /books-note -->"


def text(fragment):
    """Plain text of an HTML fragment."""
    return html_mod.unescape(re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", fragment))).strip()


def parse(item):
    """Author, year, title and publisher from one list entry, or None if it names no book."""
    m = re.search(r"<em>(.*?)</em>", item, re.S)
    if not m:
        return None
    title = text(m.group(1)).strip(" .,")
    before = text(item[:m.start()])
    after = text(item[m.end():])
    # Commentary follows a dash ("— the reference for Units 1-3"); the publisher comes before it,
    # and a clause that starts in lower case ("is open access at ...") is commentary too.
    after = re.split(r"(?:^|\s)[—–](?:\s|$)|\s-\s", after)[0].strip(" ,.;:")
    if after[:1].islower():
        after = ""
    year = re.search(r"\b(19|20)\d{2}\b", before) or re.search(r"\b(19|20)\d{2}\b", after)
    author = re.sub(r"\(\s*(19|20)\d{2}\s*\)", "", before)
    author = re.sub(r"[\s,:—–-]+$", "", author).strip(" ,")
    publisher = re.sub(r",?\s*\(?\b(19|20)\d{2}\)?\s*$", "", after).strip(" ,.()")
    publisher = re.sub(r"^(19|20)\d{2},?\s*", "", publisher)
    if publisher[:1].islower():
        publisher = ""
    if not title or len(title) < 3:
        return None
    return {"title": title, "author": author, "year": year.group(0) if year else "",
            "publisher": publisher}


def split_on(fragment, sep):
    """Split an HTML fragment on sep without cutting an entity such as &amp; in two."""
    fragment = re.sub(r"&middot;|&#183;|&#xb7;", "\u00b7", fragment)
    return [p.replace("\0", "&amp;") for p in fragment.replace("&amp;", "\0").split(sep)]


def section_items(fragment):
    """Book entries in a section: its list items (one per book, also when an item joins two
    with a middle dot), plus 'Reference: A, *X*; B, *Y*' paragraphs."""
    items = []
    for li in re.findall(r"<li>(.*?)</li>", fragment, re.S):
        items += split_on(li, "\u00b7")
    for para in re.findall(r"<p>\s*<strong>References?:?</strong>:?(.*?)</p>", fragment, re.S):
        items += [bit for piece in split_on(para, ";") for bit in split_on(piece, "\u00b7")]
    return [i for i in items if "<em>" in i]


def from_course_pages():
    """(course title, page path, entries) for each course page with a textbook section."""
    for area, _ in AREAS:
        for page in sorted((ROOT / area).glob("*/index.html")):
            if is_stub(page):
                continue
            s = page.read_text(encoding="utf-8")
            h1 = re.search(r"<h1[^>]*>(.*?)</h1>", s, re.S)
            entries = []
            for m in BOOK_HEAD.finditer(s):
                if not BOOK_WORDS.search(m.group(2)) or "Quick" in m.group(2):
                    continue
                rest = s[m.end():]
                stop = re.search(r"<h2|<div class=\"(tip|page-nav)|</section>|<!--", rest)
                entries += section_items(rest[:stop.start()] if stop else rest)
            if entries and h1:
                yield text(h1.group(1)), page.relative_to(ROOT).as_posix(), entries


def from_readmes():
    """The same for the Data Science READMEs' textbook sections."""
    for course in _bs.COURSES:
        readme = ROOT / "data-science" / course["src"] / "README.md"
        if not readme.exists():
            continue
        md = readme.read_text(encoding="utf-8")
        m = MD_HEAD.search(md)
        if not m:
            continue
        nxt = re.search(r"^## ", md[m.end():], re.M)
        part = md[m.end(): m.end() + nxt.start()] if nxt else md[m.end():]
        yield (course["title"], f"data-science/{course['slug']}/index.html",
               section_items(_bs.render_markdown(part)))


def key(title):
    return re.sub(r"[^a-z0-9]", "", title.lower())


def surnames(author):
    return {w for w in re.findall(r"[a-z]{3,}", author.lower()) if w not in ("and", "the")}


def collect():
    """Books keyed by title; two books that share a title but no author name stay apart."""
    books = {}
    for course, path, entries in list(from_course_pages()) + list(from_readmes()):
        for item in entries:
            b = parse(item)
            if not b:
                continue
            same = [k for k, have in books.items() if key(have["title"]) == key(b["title"]) and (
                not have["author"] or not b["author"] or surnames(have["author"]) & surnames(b["author"]))]
            k = same[0] if same else f"{key(b['title'])}#{len(books)}"
            have = books.setdefault(k, {**b, "courses": {}})
            for field in ("author", "year", "publisher"):
                if len(b[field]) > len(have[field]):
                    have[field] = b[field]
            have["courses"][path] = course
    return books


def area_of(book):
    first = sorted(book["courses"])[0].split("/")[0]
    return first if first in dict(AREAS) else "statistics"


def amazon(book):
    surname = re.split(r"[,&]| and ", book["author"])[0].split()[-1:] if book["author"] else []
    url = "https://www.amazon.in/s?k=" + quote_plus(" ".join([book["title"]] + surname)) + "&i=stripbooks"
    return url + (f"&tag={quote_plus(AMAZON_TAG)}" if AMAZON_TAG else "")


def render(books):
    esc = html_mod.escape
    rel = ' rel="sponsored noopener"' if AMAZON_TAG else ' rel="noopener"'
    blocks, rail = [], []
    for area, name in AREAS:
        mine = sorted((b for b in books.values() if area_of(b) == area), key=lambda b: key(b["title"]))
        if not mine:
            continue
        rail.append(f'<a href="#{area}">{name}</a>')
        rows = []
        for b in mine:
            by = ", ".join(x for x in (b["author"], b["year"]) if x)
            courses = " · ".join(f'<a href="{esc(p)}">{esc(c)}</a>' for p, c in sorted(
                b["courses"].items(), key=lambda kv: kv[1]))
            pub = f'{esc(b["publisher"])}. ' if b["publisher"] else ""
            rows.append(
                f'      <dt><cite>{esc(b["title"])}</cite>{" — " + esc(by) if by else ""}</dt>\n'
                f'      <dd>{pub}Recommended in: {courses}. '
                f'<a href="{esc(amazon(b))}" target="_blank"{rel}>Find on Amazon.in</a></dd>')
        blocks.append(f'  <section class="letter" id="{area}">\n    <h2>{name}</h2>\n    <dl>\n'
                      + "\n".join(rows) + "\n    </dl>\n  </section>")
    n = len(books)
    n_courses = len({p for b in books.values() for p in b["courses"]})
    note = (f"<p class=\"lede\">{DISCLOSURE}</p>" if AMAZON_TAG else
            "<p class=\"lede\">The links search Amazon.in for each title.</p>")
    desc = (f"The {n} textbooks recommended across {n_courses} StatsTricks360 courses in statistics "
            "and data science, each with the courses that use it.")
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>Books We Recommend — StatsTricks360</title>
<meta name="description" content="{desc}">
<meta property="og:title" content="Books We Recommend — StatsTricks360">
<meta property="og:description" content="{desc}">
<meta property="og:type" content="website">
<meta property="og:site_name" content="StatsTricks360">
<meta name="twitter:card" content="summary">
<meta property="og:url" content="{SITE_BASE}/books.html">
<meta name="theme-color" content="#0f4c81">
<link rel="canonical" href="{SITE_BASE}/books.html">
<link rel="stylesheet" href="assets/nrstatlab.css">
</head>
<body>

<header class="topics-head">
  <div class="wrap">
    <p class="eyebrow"><a href="index.html">StatsTricks360</a> &rsaquo; Books</p>
    <h1>Books we recommend</h1>
    <p class="lede">{n} textbooks named on {n_courses} course pages, gathered in one place, with the
    courses that use each. Every page on this site stays free to read; these are for the reader who
    wants the book on the desk as well.</p>
    {note}
    <nav class="alpha" aria-label="Jump to a section">
      {" ".join(rail)}
    </nav>
  </div>
</header>

<main class="wrap topics">
{chr(10).join(blocks)}
</main>

<footer>
  <div class="wrap">
    <span><b>StatsTricks360</b> &mdash; study material for statistics and data science</span>
    <span><a href="index.html">Back to the home page</a></span>
  </div>
</footer>

</body>
</html>
"""


def about_note():
    if AMAZON_TAG:
        body = ("The <a href=\"books.html\">Books page</a> links to Amazon.in. " + DISCLOSURE +
                " Those are ordinary links: this site still sets no cookies, and Amazon&rsquo;s own "
                "privacy notice applies once you are on its site.")
    else:
        body = ("The <a href=\"books.html\">Books page</a> links to Amazon.in so that you can find "
                "each recommended book. Those are ordinary links: this site sets no cookies, and "
                "Amazon&rsquo;s own privacy notice applies once you are on its site.")
    return f"{NOTE_START}\n    <p>{body}</p>\n    {NOTE_END}"


def with_about_note(s):
    block = re.compile(re.escape(NOTE_START) + r".*?" + re.escape(NOTE_END), re.S)
    if block.search(s):
        return block.sub(lambda _: about_note(), s)
    anchor = '    <h2 id="privacy">Privacy</h2>\n'
    assert s.count(anchor) == 1, "about.html: privacy heading not found"
    i = s.index("</p>\n", s.index(anchor)) + len("</p>\n")
    return s[:i] + "    " + about_note() + "\n" + s[i:]


def main(apply=False):
    books = collect()
    by_area = {a: sum(area_of(b) == a for b in books.values()) for a, _ in AREAS}
    print(f"{len(books)} books from {len({p for b in books.values() for p in b['courses']})} courses "
          f"({', '.join(f'{a} {n}' for a, n in by_area.items())}); tag {'set' if AMAZON_TAG else 'not set'}")
    if apply:
        OUT.write_text(render(books), encoding="utf-8")
        ABOUT.write_text(with_about_note(ABOUT.read_text(encoding="utf-8")), encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)} and the note in {ABOUT.relative_to(ROOT)}")
    else:
        print("dry run -- pass --apply to write")


if __name__ == "__main__":
    main(apply="--apply" in sys.argv)
